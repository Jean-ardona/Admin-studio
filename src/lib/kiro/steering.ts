import { enabledNavItems, modelSlug } from "../generator/naming";
import type { GeneratedFile } from "@/lib/generator/types";
import type { Field } from "@/lib/parser";
import type { ModelPermissions, StudioConfig, StudioPage } from "@/lib/studio-config";

const PERMISSION_KEYS: (keyof ModelPermissions)[] = ["view", "create", "edit", "delete"];

/** Short description of a field, e.g. "email: String (unique)" or "posts: Post[] (relation)". */
const describeField = (field: Field): string => {
  const type = `${field.type}${field.isList ? "[]" : ""}${field.isOptional ? "?" : ""}`;
  const flags = [
    field.isId ? "id" : "",
    field.isUnique ? "unique" : "",
    field.kind === "relation" ? "relation" : "",
    field.kind === "enum" ? "enum" : "",
  ].filter(Boolean);
  return `${field.name}: ${type}${flags.length ? ` (${flags.join(", ")})` : ""}`;
};

const pagesOf = (config: StudioConfig, model: string): StudioPage[] =>
  config.models[model]?.enabledPages ?? [];

const modelList = (config: StudioConfig): string =>
  config.schema.models.length === 0
    ? "- (no models)"
    : config.schema.models.map((m) => `- ${m.name}`).join("\n");

/** steering/product.md: what this project is and which models and roles it has. */
export const productSteeringTemplate = (config: StudioConfig): string => {
  const roles =
    config.roles.length === 0
      ? "- (no roles defined)"
      : config.roles.map((r) => `- ${r.name}`).join("\n");
  return `# Product

This project is an admin dashboard generated by Prisma Admin Studio from a Prisma schema.
It is a Next.js (App Router) app using Prisma with SQLite, Tailwind CSS and role-based access.

## Models
${modelList(config)}

## Roles
${roles}

## Principles
- The Prisma schema (\`prisma/schema.prisma\`) is the source of truth for data.
- \`lib/roles.ts\` is the single source of truth for roles and permissions.
- All UI text is in English.
`;
};

/** steering/structure.md: folder layout plus the real models, their fields and pages. */
export const structureSteeringTemplate = (config: StudioConfig): string => {
  const nav = enabledNavItems(config);
  const modelSections = config.schema.models
    .map((model) => {
      const slug = modelSlug(model.name);
      const cfg = config.models[model.name];
      const pages = pagesOf(config, model.name);
      const fields = model.fields.map((f) => `  - ${describeField(f)}`).join("\n");
      const columns = cfg
        ? cfg.columns.filter((c) => c.visible).map((c) => c.field).join(", ")
        : "";
      return `### ${model.name}
- Route: \`/${slug}\` (files in \`app/${slug}/\`, \`components/${slug}-table.tsx\`${pages.includes("create") || pages.includes("edit") ? `, \`components/${slug}-form.tsx\`` : ""})
- Enabled pages: ${pages.length ? pages.join(", ") : "none"}
- Visible table columns: ${columns || "none"}
- Fields:
${fields}`;
    })
    .join("\n\n");

  const enums = config.schema.enums.length
    ? `\n## Enums\n${config.schema.enums.map((e) => `- ${e.name}: ${e.values.join(", ")}`).join("\n")}\n`
    : "";

  return `# Structure

## Folders
- \`prisma/schema.prisma\`: data model. \`prisma/seed.ts\`: seed script.
- \`app/\`: one folder per model (\`app/<model-slug>/\`) with list, detail, new and edit pages plus \`actions.ts\` (server actions).
- \`components/\`: sidebar, top bar, role switcher, and one table and form per model.
- \`lib/\`: \`prisma.ts\` (client), \`roles.ts\` (roles and permissions), \`current-role.ts\`, \`navigation.ts\`, \`format.ts\`.

## Sidebar entries
${nav.length ? nav.map((n) => `- ${n.label} -> \`${n.href}\``).join("\n") : "- (none)"}

## Models
${modelSections || "(no models)"}
${enums}`;
};

/** steering/roles.md: every role with its real permissions and menu. */
export const rolesSteeringTemplate = (config: StudioConfig): string => {
  const models = config.schema.models.map((m) => m.name);
  const roleSections = config.roles
    .map((role) => {
      const rows = models
        .map((model) => {
          const p = role.permissions[model];
          const allowed = PERMISSION_KEYS.filter((k) => p?.[k]);
          return `  - ${model}: ${allowed.length ? allowed.join(", ") : "no access"}`;
        })
        .join("\n");
      const menu = role.menu.filter((m) => models.includes(m));
      return `### ${role.name}
- Menu: ${menu.length ? menu.join(", ") : "empty"}
- Permissions:
${rows || "  - (no models)"}`;
    })
    .join("\n\n");

  return `# Roles

Roles and permissions live in one file: \`lib/roles.ts\`. Edit it there and nowhere else.

## How it works
- \`can(role, model, action)\` answers whether a role may \`view\`, \`create\`, \`edit\` or \`delete\` a model.
- The sidebar shows only the menu entries of the current role.
- Pages and server actions call \`can()\` and render the not-allowed view or reject the request when access is missing.
- The role switcher in the top bar changes the current role (stored in a cookie, read by \`lib/current-role.ts\`).

## Current roles
${roleSections || "(no roles defined)"}
`;
};

/** steering/conventions.md: code conventions of the generated project. */
export const conventionsSteeringTemplate = (config: StudioConfig): string => {
  const example = config.schema.models[0];
  const slug = example ? modelSlug(example.name) : "<model-slug>";
  const name = example ? example.name : "<Model>";
  return `# Conventions

- Language: TypeScript. Framework: Next.js App Router with server components by default.
- Styling: Tailwind CSS. All UI text is in English.
- Database: Prisma with SQLite. After editing \`prisma/schema.prisma\`, run \`npx prisma db push\` and \`npx prisma generate\`.
- Routes use the kebab-case model name. Example: \`${name}\` lives in \`app/${slug}/\`.
- Mutations are server actions in \`app/<model-slug>/actions.ts\`, and each one checks \`can()\` first.
- Never hard-code permission checks. Use \`can()\` from \`lib/roles.ts\`.
- When adding a model, also add its permissions to every role in \`lib/roles.ts\` and an entry to \`lib/navigation.ts\`.
- Keep files small and commented so changes stay easy to review.
`;
};

/** Builds the four steering files for the generated project from the real config. Pure. */
export const generateSteering = (config: StudioConfig): GeneratedFile[] => [
  { path: ".kiro/steering/product.md", content: productSteeringTemplate(config) },
  { path: ".kiro/steering/structure.md", content: structureSteeringTemplate(config) },
  { path: ".kiro/steering/roles.md", content: rolesSteeringTemplate(config) },
  { path: ".kiro/steering/conventions.md", content: conventionsSteeringTemplate(config) },
];
