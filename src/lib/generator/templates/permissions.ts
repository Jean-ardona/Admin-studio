/**
 * Permission enforcement files of the generated project.
 * Roles and permissions themselves live in lib/roles.ts (single source of truth).
 * These files only read the active role and apply `can()` and the role menu.
 * Pure: no config needed, the output is always the same.
 */

/** lib/current-role.ts: server-only helpers to read the active role and its visible menu. */
export const currentRoleTemplate = (): string => `import { cookies } from "next/headers";

import { navItems, type NavItem } from "@/lib/navigation";
import { ROLE_COOKIE, can, getRole, roles } from "@/lib/roles";

/**
 * Name of the active role, read from the role cookie.
 * Falls back to the first role when the cookie is missing or unknown.
 * Pass the result to can(role, model, action) from lib/roles.ts.
 */
export async function getActiveRole(): Promise<string | undefined> {
  const cookieStore = await cookies();
  return (getRole(cookieStore.get(ROLE_COOKIE)?.value) ?? roles[0])?.name;
}

/**
 * Sidebar entries of the active role: the model must be in the role's menu
 * and the role must be allowed to view it.
 */
export async function getVisibleNavItems(): Promise<NavItem[]> {
  const roleName = await getActiveRole();
  const menu: string[] = getRole(roleName)?.menu ?? [];
  return navItems.filter((item) => menu.includes(item.model) && can(roleName, item.model, "view"));
}
`;

/** components/not-allowed.tsx: message shown when the active role may not open a page. */
export const notAllowedTemplate = (): string => `/** Shown instead of a page when the active role lacks the required permission. */
export function NotAllowed() {
  return (
    <section className="max-w-xl rounded-2xl border border-border bg-surface p-6">
      <h1 className="text-lg font-semibold">Not allowed</h1>
      <p className="mt-2 text-sm text-muted">
        Your current role does not have permission to see this page. Switch role in the top bar to continue.
      </p>
    </section>
  );
}
`;

/** app/layout.tsx: like the skeleton layout, but the sidebar only gets the active role's menu. */
export const roleLayoutTemplate = (): string => `import type { Metadata } from "next";
import type { ReactNode } from "react";

import { Sidebar } from "@/components/sidebar";
import { TopBar } from "@/components/top-bar";
import { getVisibleNavItems } from "@/lib/current-role";

import "./globals.css";

export const metadata: Metadata = {
  title: "Admin dashboard",
  description: "Admin dashboard generated by Prisma Admin Studio",
};

export default async function RootLayout({ children }: { children: ReactNode }) {
  // Menu entries allowed for the active role (see lib/roles.ts).
  const items = await getVisibleNavItems();

  return (
    <html lang="en">
      <body className="flex min-h-screen">
        <Sidebar items={items} />
        <div className="flex min-w-0 flex-1 flex-col">
          <TopBar />
          <main className="flex-1 p-6">{children}</main>
        </div>
      </body>
    </html>
  );
}
`;

/** app/page.tsx: opens the first model the active role can see. */
export const roleHomePageTemplate = (): string => `import { redirect } from "next/navigation";

import { getVisibleNavItems } from "@/lib/current-role";

// Always evaluate the active role on each request.
export const dynamic = "force-dynamic";

/** Opens the first menu entry of the active role, or shows a hint when it has none. */
export default async function HomePage() {
  const [first] = await getVisibleNavItems();
  if (first) redirect(first.href);
  return <p className="text-muted">The current role has no models in its menu.</p>;
}
`;

/** components/sidebar.tsx: client component that shows the items it receives (already filtered by role). */
export const roleSidebarTemplate = (): string => `"use client";

import Link from "next/link";
import { usePathname } from "next/navigation";

import type { NavItem } from "@/lib/navigation";

/** Left navigation. Items are filtered by the active role in app/layout.tsx. */
export function Sidebar({ items }: { items: NavItem[] }) {
  const pathname = usePathname();

  return (
    <aside className="sticky top-0 flex h-screen w-60 shrink-0 flex-col border-r border-border bg-surface p-4">
      <div className="mb-6 px-2 text-lg font-semibold tracking-tight">Admin</div>
      <nav className="flex flex-col gap-1">
        {items.map((item) => {
          const active = pathname === item.href || pathname.startsWith(\`\${item.href}/\`);
          return (
            <Link
              key={item.model}
              href={item.href}
              className={
                active
                  ? "rounded-lg bg-raised px-3 py-2 text-sm text-accent-bright"
                  : "rounded-lg px-3 py-2 text-sm text-muted hover:bg-raised hover:text-foreground"
              }
            >
              {item.label}
            </Link>
          );
        })}
      </nav>
    </aside>
  );
}
`;
