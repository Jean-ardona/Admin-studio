/** Home page: sends visitors to the first enabled model, or shows a hint when there is none. */
export const homePageTemplate = (items: NavItem[]): string =>
  items.length > 0
    ? `import { redirect } from "next/navigation";

// The dashboard has no landing page of its own: open the first model.
export default function HomePage() {
  redirect(${JSON.stringify(items[0].href)});
}
`
    : `// No models are enabled in the sidebar yet.
export default function HomePage() {
  return <p className="text-muted">No models are enabled.</p>;
}
`;

/** Navigation data. Edit this file to rename, reorder or add menu entries. */
export const navigationTemplate = (items: NavItem[]): string => `/** One sidebar entry. */
export type NavItem = {
  /** Prisma model name. */
  model: string;
  /** Text shown in the sidebar. */
  label: string;
  /** Route of the model's list page. */
  href: string;
};

/** Menu entries, generated from the models enabled in Prisma Admin Studio. */
export const navItems: NavItem[] = ${JSON.stringify(items, null, 2)};
`;

/** Sidebar client component, highlights the active route. */
export const sidebarTemplate = (): string => `"use client";

import Link from "next/link";
import { usePathname } from "next/navigation";

import { navItems } from "@/lib/navigation";

/** Left navigation. The menu comes from lib/navigation.ts. */
export function Sidebar() {
  const pathname = usePathname();

  return (
    <aside className="sticky top-0 flex h-screen w-60 shrink-0 flex-col border-r border-border bg-surface p-4">
      <div className="mb-6 px-2 text-lg font-semibold tracking-tight">Admin</div>
      <nav className="flex flex-col gap-1">
        {navItems.map((item) => {
          const active = pathname === item.href || pathname.startsWith(\`\${item.href}/\`);
          return (
            <Link
              key={item.model}
              href={item.href}
              className={
                active
                  ? "rounded-lg bg-raised px-3 py-2 text-sm text-accent-bright"
                  : "rounded-lg px-3 py-2 text-sm text-muted hover:bg-raised hover:text-foreground"
              }
            >
              {item.label}
            </Link>
          );
        })}
      </nav>
    </aside>
  );
}
`;

